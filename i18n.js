  const plural = (n, one, many) => `${n} ${+n === 1 ? one : many}`;
  const RULES = [
    [/^(\d+) tests?( ·)?$/, (m) => plural(m[1], "prueba", "pruebas") + (m[2] || "")],
    [/^(\d+) defects?$/, (m) => plural(m[1], "defecto", "defectos")],
    [/^(.+), (\d+) tests?$/, (m) => `${tr(m[1]) ?? m[1]}, ${plural(m[2], "prueba", "pruebas")}`],
    [/^(.+) · (\d+) tests?$/, (m) => `${tr(m[1]) ?? m[1]} · ${plural(m[2], "prueba", "pruebas")}`],
    [/^Known defect · (D\d)$/, (m) => `Defecto conocido · ${m[1]}`],
    [/^# (.+)$/, (m) => (tr(m[1]) ? `# ${tr(m[1])}` : null)],
  ];
  function tr(text) {
    if (ES[text]) return ES[text];
    for (const [re, fn] of RULES) { const m = text.match(re); if (m) return fn(m); }
    return null;
  }

  const ATTRS = ["aria-label", "title"];
  const original = new Map(); // text node or "element|attr" → English text
  const shown = new WeakMap(); // text node → the Spanish we put there
  let lang = "en";

  const doText = (n) => {
    // a script may have replaced the text since we translated it: that is the new English
    if (!original.has(n) || n.nodeValue !== shown.get(n)) original.set(n, n.nodeValue);
    const en = original.get(n);
    const key = en.replace(/\s+/g, " ").trim();
    const es = key && tr(key);
    if (!es) return;
    const out = en.match(/^\s*/)[0] + es + en.match(/\s*$/)[0];
    if (n.nodeValue !== out) n.nodeValue = out;
    shown.set(n, out);
  };
  const doAttrs = (el) => {
    for (const a of ATTRS) {
      if (!el.hasAttribute(a)) continue;
      if (!el.hasAttribute("data-en-" + a)) el.setAttribute("data-en-" + a, el.getAttribute(a));
      const es = tr(el.getAttribute("data-en-" + a));
      if (es) el.setAttribute(a, es);
    }
  };
